-- Then connect as auth_app and run:
-- ROLE is one of EMPLOYEE, MANAGER, ADMIN (see com.auth.entity.Role).
CREATE TABLE APP_USERS (
    USER_ID   NUMBER(19) PRIMARY KEY,
    NAME      VARCHAR2(100 CHAR) NOT NULL,
    EMAIL     VARCHAR2(150 CHAR) NOT NULL UNIQUE,
    PASSWORD  VARCHAR2(255 CHAR) NOT NULL,
    ROLE      VARCHAR2(20 CHAR) DEFAULT 'EMPLOYEE' NOT NULL
);

CREATE SEQUENCE APP_USER_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;
